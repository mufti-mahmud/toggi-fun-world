/**
 * Converts a YouTube watch, shorts, or share link into an embeddable URL
 */
export function toEmbedUrl(url: string): string {
  const trimmed = (url || '').trim();
  if (!trimmed) return '';
  if (trimmed.includes('youtube.com/embed/')) return trimmed;

  // Match youtube.com/watch?v=ID
  const watchMatch = trimmed.match(/[?&]v=([a-zA-Z0-9_-]{6,})/);
  if (watchMatch?.[1]) {
    return `https://www.youtube.com/embed/${watchMatch[1]}?autoplay=1&rel=0`;
  }

  // Match youtube.com/shorts/ID
  const shortsMatch = trimmed.match(/youtube\.com\/shorts\/([a-zA-Z0-9_-]{6,})/);
  if (shortsMatch?.[1]) {
    return `https://www.youtube.com/embed/${shortsMatch[1]}?autoplay=1&rel=0`;
  }

  // Match youtu.be/ID
  const shortLinkMatch = trimmed.match(/youtu\.be\/([a-zA-Z0-9_-]{6,})/);
  if (shortLinkMatch?.[1]) {
    return `https://www.youtube.com/embed/${shortLinkMatch[1]}?autoplay=1&rel=0`;
  }

  return trimmed;
}

/**
 * Normalizes floor labels like "Level10" -> "Level 10", "Level09" -> "Level 09"
 */
export function normalizeFloor(floor: string): string {
  const f = (floor || '').trim();
  return f.replace(/^Level\s*(\d+)$/i, (_, num) => `Level ${num.padStart(2, '0')}`);
}

